/* ═══════════════════════════════════════════════════════════════════════════
   Kernel I/O records of the traversal kernels (k_intersect / k_shadow) — the
   single source of truth for their byte layouts, like bvh/layout.ts is for
   the acceleration structures. emitWgslRays() produces the matching WGSL;
   the kernel loader (kernels.ts) prepends it to every kernel.

   Ray record, 32 B (two 16-byte rows):
     byte  0  o     vec3f   origin (world)
     byte 12  tmin  f32
     byte 16  d     vec3f   direction (world, need not be normalised:
                            t is measured in units of |d|)
     byte 28  tmax  f32     always finite (DECISIONS.md #3): 1e30 for camera /
                            indirect rays, light distance × (1 − ε) for shadow rays
   Hit record, 24 B (scalars only → 4-byte aligned, array stride 24):
     byte  0  t     f32     0 on a miss
     byte  4  u     f32     barycentrics: P = (1−u−v)·v0 + u·v1 + v·v2
     byte  8  v     f32
     byte 12  inst  u32     instance index, NO_INDEX for single-level traces / misses
     byte 16  tri   u32     absolute triangle record index, NO_INDEX on a miss
     byte 20  flags u32     bit 0 = frontFace (det > 0 in object space: the
                            geometric normal (v1−v0)×(v2−v0) faces the ray)
   Kernel params (uniform), 16 B: count, mask (visibility bits), root (node
   index: PackedScene.tlasRoot, or a BLAS root in single-level mode), mode
   (bit 0 = single-level BLAS trace).
   Debug counters (storage, atomics), 16 B: stackOverflow (DECISIONS.md #1)
   + 3 reserved words.
   Occlusion output of k_shadow: one u32 per ray (1 = occluded).
   ═══════════════════════════════════════════════════════════════════════════ */

export type IoFieldType = 'vec3f' | 'vec4f' | 'u32' | 'f32' | 'atomic<u32>';

export interface IoStructDef {
  name: string;
  size: number;
  fields: { name: string; type: IoFieldType; offset: number }[];
}

export const RAY_BYTES = 32;
export const RAY_WORDS = 8;
export const RAY_OFFSETS = { o: 0, tmin: 12, d: 16, tmax: 28 } as const;
export const RAY_W = { o: 0, tmin: 3, d: 4, tmax: 7 } as const;

export const HIT_BYTES = 24;
export const HIT_WORDS = 6;
export const HIT_OFFSETS = { t: 0, u: 4, v: 8, inst: 12, tri: 16, flags: 20 } as const;
export const HIT_W = { t: 0, u: 1, v: 2, inst: 3, tri: 4, flags: 5 } as const;
export const HIT_FRONT = 1;

export const PARAMS_BYTES = 16;
export const PARAMS_OFFSETS = { count: 0, mask: 4, root: 8, mode: 12 } as const;
export const PARAMS_W = { count: 0, mask: 1, root: 2, mode: 3 } as const;
/** params.mode bit: trace one BLAS from `root` instead of the two-level scene */
export const MODE_SINGLE_LEVEL = 1;

export const DBG_BYTES = 16;
export const DBG_OFFSETS = { stackOverflow: 0, r0: 4, r1: 8, r2: 12 } as const;
export const DBG_W = { stackOverflow: 0, r0: 1, r1: 2, r2: 3 } as const;

/** "no instance / no triangle" */
export const NO_INDEX = 0xffffffff;
/** tmax of camera and indirect rays (DECISIONS.md #3) */
export const T_INFINITE = 1e30;

export const IO_STRUCTS: IoStructDef[] = [
  {
    name: 'B5Ray',
    size: RAY_BYTES,
    fields: [
      { name: 'o', type: 'vec3f', offset: RAY_OFFSETS.o },
      { name: 'tmin', type: 'f32', offset: RAY_OFFSETS.tmin },
      { name: 'd', type: 'vec3f', offset: RAY_OFFSETS.d },
      { name: 'tmax', type: 'f32', offset: RAY_OFFSETS.tmax }
    ]
  },
  {
    name: 'B5HitRec',
    size: HIT_BYTES,
    fields: [
      { name: 't', type: 'f32', offset: HIT_OFFSETS.t },
      { name: 'u', type: 'f32', offset: HIT_OFFSETS.u },
      { name: 'v', type: 'f32', offset: HIT_OFFSETS.v },
      { name: 'inst', type: 'u32', offset: HIT_OFFSETS.inst },
      { name: 'tri', type: 'u32', offset: HIT_OFFSETS.tri },
      { name: 'flags', type: 'u32', offset: HIT_OFFSETS.flags }
    ]
  },
  {
    name: 'B5KernelParams',
    size: PARAMS_BYTES,
    fields: [
      { name: 'count', type: 'u32', offset: PARAMS_OFFSETS.count },
      { name: 'mask', type: 'u32', offset: PARAMS_OFFSETS.mask },
      { name: 'root', type: 'u32', offset: PARAMS_OFFSETS.root },
      { name: 'mode', type: 'u32', offset: PARAMS_OFFSETS.mode }
    ]
  },
  {
    name: 'B5Dbg',
    size: DBG_BYTES,
    fields: [
      { name: 'stackOverflow', type: 'atomic<u32>', offset: DBG_OFFSETS.stackOverflow },
      { name: 'r0', type: 'atomic<u32>', offset: DBG_OFFSETS.r0 },
      { name: 'r1', type: 'atomic<u32>', offset: DBG_OFFSETS.r1 },
      { name: 'r2', type: 'atomic<u32>', offset: DBG_OFFSETS.r2 }
    ]
  }
];

/** WGSL declarations of the I/O structs + constants (B5/b5_ prefixed, no `$`). */
export function emitWgslRays(): string {
  const lines: string[] = ['// generated by pathtracer/rays.ts — do not edit'];
  lines.push(`const B5_NO_INDEX: u32 = 0x${NO_INDEX.toString(16)}u;`);
  lines.push(`const B5_HIT_FRONT: u32 = ${HIT_FRONT}u;`);
  lines.push(`const B5_MODE_SINGLE_LEVEL: u32 = ${MODE_SINGLE_LEVEL}u;`);
  lines.push(`const B5_T_INFINITE: f32 = ${T_INFINITE.toExponential()};`);
  lines.push('');
  for (const s of IO_STRUCTS) {
    lines.push(`// size ${s.size} B`);
    lines.push(`struct ${s.name} {`);
    for (const f of s.fields) lines.push(`  ${f.name}: ${f.type}, // @${f.offset}`);
    lines.push('}');
    lines.push('');
  }
  return lines.join('\n');
}

/** Write one ray record (f32 rounding happens here, so the CPU reference must read the buffer back). */
export function writeRay(
  F: Float32Array, i: number,
  ox: number, oy: number, oz: number, dx: number, dy: number, dz: number,
  tmin: number, tmax: number
): void {
  const w = i * RAY_WORDS;
  F[w + RAY_W.o] = ox; F[w + RAY_W.o + 1] = oy; F[w + RAY_W.o + 2] = oz;
  F[w + RAY_W.tmin] = tmin;
  F[w + RAY_W.d] = dx; F[w + RAY_W.d + 1] = dy; F[w + RAY_W.d + 2] = dz;
  F[w + RAY_W.tmax] = tmax;
}
