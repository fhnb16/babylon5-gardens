/* ═══════════════════════════════════════════════════════════════════════════
   Tracer-only constants (PT-W4a). Everything the path tracer tunes that is
   not part of the shared world description lives here, NOT in core/config
   (owned by the lead). Two groups:

   • numerical knobs of lights / BSDFs (water, glass, light selection);
   • PHYS_OVERRIDE — the CALIBRATED physical palette (pathtracer/tools/
     calibrate.ts computes it; the lead moves it into CORE_CONFIG.PHYS).
     tracerLightingAt(phase) = core lightingAt() with that palette, so every
     tracer page uses the calibrated values until core has them.
   ═══════════════════════════════════════════════════════════════════════════ */

import { CORE_CONFIG, type PhysPalette } from '../core/config/index.ts';
import { lightingAt } from '../core/lighting/phases.ts';
import { FOAM_COLOR } from '../core/shading/contracts.ts';
import { HULL_CONST } from '../core/shading/kernels/hull.ts';
import type { LightingState, PhaseId } from '../core/scene/types.ts';

/** Water BSDF (bsdf_water.wgsl), hull kind with a water weight. */
export const WATER_PT = {
  /** refractive index of the water surface */
  ior: 1.33,
  /** multiplier of the Fresnel reflectance of the top interface (art knob; 1 = physical) */
  f0Boost: 1,
  /**
   * station units of water depth per unit of the hull mask's water weight.
   * Beer–Lambert: Tr = exp(−σ · depth · (1/cosT_o + 1/cosT_i) / 2) with
   * σ · depthScale = HULL_CONST.absorbK, so at normal incidence the absorption
   * equals the raster's mix(bed, waterTint, 1 − exp(−absorbK · w)).
   */
  depthScale: 0.25
} as const;

/** Thin dielectric glazing (bsdf_glass.wgsl). Tint / IOR come from the material. */
export const GLASS_PT = {
  /** smallest |cos| used in the Fresnel term of shadow transmission */
  minCos: 1e-3
} as const;

/** Light sampling (lights.wgsl, lights/*.ts). */
export const LIGHTS_PT = {
  /** clamp of the probability to sample the tube vs the triangle lights */
  pTubeMin: 0.05,
  pTubeMax: 0.95,
  /** k_lightpower: stratified points per emissive triangle (4×4) */
  powerSamplesSide: 4,
  /** k_lightpower: ray-cone width = sqrt(world area) × this (texture LOD of the power estimate) */
  powerConeScale: 0.25,
  /** light-tree builder: SAH-like buckets per axis (pbrt-v4 BVHLightSampler) */
  treeBuckets: 12,
  /** relative radius under which the shading point counts as inside the tube */
  tubeInsideEps: 1e-4
} as const;

/** Tube NEE strategies (B5Frame.tubeMode). */
export const TUBE_MODE = { uniformArea: 0, equiangular: 1 } as const;
/** Triangle-light selection strategies (B5Frame.lightMode). */
export const LIGHT_MODE = { none: 0, alias: 1, tree: 2 } as const;

/**
 * Raster tone-mapping exposure (app/boot.ts / tools/core-world.ts:
 * renderer.toneMappingExposure). The tracer outputs the raster's PRE-tonemap
 * radiance; viewers apply this before three's ACES filmic curve.
 */
export const RASTER_TONE_EXPOSURE = 1.22;

/*
   Calibrated physical palette (pathtracer/tools/calibrate.ts, see the report
   of unit PT-W4a). Policy: the camera EV100 of the first guess is kept
   (12.5 / 11 / 6.5), the luminances are solved so that exposure-scaled
   radiance matches the raster:
     tube      — the traced floor irradiance (direct tube + indirect, closed
                 cylinder estimate) equals the raster hemisphere + axis
                 point-light irradiance averaged over the habitat floor;
     channels  — nits × exposure = the raster emissive intensity of the
                 channel at that phase (windows: winEmis, tower glass / endcap:
                 winEmis·0.45, lift glass: lerp(1.4, 0.3, daylight), traffic
                 body: trafficWindow, traffic lamp: trafficLamp, lift lamp: 1
                 (colour is HDR in the material), beacon: 0.2 + night,
                 cityGlow: cityGlow, nav: navInt).
   Values are rounded to 3 significant digits.
*/
/* Moved into CORE_CONFIG.PHYS by the lead (2026-11-19); kept as an alias so
   existing imports and calibrate.test.ts (tool output == this table) still work. */
export const PHYS_OVERRIDE: Record<PhaseId, PhysPalette> = CORE_CONFIG.PHYS;
/** CORE_CONFIG with the calibrated palette (lightingAt's cfg argument). */
export const TRACER_CONFIG = { ...CORE_CONFIG, PHYS: PHYS_OVERRIDE } as typeof CORE_CONFIG;

/** lightingAt(phase) with the calibrated tracer palette (PHYS_OVERRIDE). */
export function tracerLightingAt(phase: number): LightingState {
  return lightingAt(phase, TRACER_CONFIG);
}

const f = (x: number) => {
  const s = Number(x).toPrecision(9);
  return /[.eE]/.test(s) ? s : s + '.0';
};

