/* ═══════════════════════════════════════════════════════════════════════════
   СЕРВИС-ВОРКЕР

   Нужен ровно для одного: без него браузер не считает страницу устанавливаемой
   и не предлагает добавить на экран. Кеша здесь нет и не должно быть — каждый
   запрос уходит в сеть, иначе правки не доедут до уже открытых вкладок.

   Версия импортируется, а не дублируется: три места с одним номером однажды
   разойдутся. Её смена меняет содержимое воркера, и браузер обновляет его сам.
   ═══════════════════════════════════════════════════════════════════════════ */
import { VERSION } from './js/version.js';

self.__VERSION = VERSION;
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', e => e.waitUntil(self.clients.claim()));
self.addEventListener('fetch', () => { /* сквозной проход, без кеша */ });
